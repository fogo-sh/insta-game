#!/usr/bin/env python3
"""Generate the Go controller and image-build services from game metadata."""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).parent
OUTPUT = ROOT / "compose.yml"


def generate():
    games = [json.loads(path.read_text()) for path in sorted((ROOT / "docker-containers").glob("*/game.json"))]
    services = {
        "controller": {
            "build": {"context": ".", "dockerfile": "Dockerfile"},
            "network_mode": "host",
            "command": [
                "serve", "--listen", "127.0.0.1:3000", "--data", "/data",
                "--catalog", "/opt/games", "--public-host", "${PUBLIC_HOST:-localhost}",
                "--game-bind", "${GAME_BIND:-127.0.0.1}",
            ],
            "volumes": ["/var/run/docker.sock:/var/run/docker.sock", "./.insta-game:/data"],
            "environment": {
                game["dataUrlEnv"]: "${" + game["dataUrlEnv"] + ":-}"
                for game in games if game.get("dataUrlEnv")
            },
        }
    }
    for game in games:
        services[game["id"]] = {
            "profiles": ["images"],
            "image": game.get("image", "ghcr.io/fogo-sh/insta-game:" + game["id"]),
            "build": {
                "context": ".",
                "dockerfile": "docker-containers/" + game["id"] + "/Dockerfile",
                "platforms": ["${GAME_PLATFORM:-linux/arm64}"],
            },
        }
    return "# Generated by generate-compose.py; game services are image-build targets.\n" + json.dumps({"services": services}, indent=2) + "\n"


def main():
    result = generate()
    if "--check" in sys.argv:
        if not OUTPUT.exists() or OUTPUT.read_text() != result:
            raise SystemExit("compose.yml is out of date; run python3 generate-compose.py")
        print("compose.yml is up to date.")
    else:
        OUTPUT.write_text(result)
        print("Generated compose.yml")


if __name__ == "__main__":
    main()
